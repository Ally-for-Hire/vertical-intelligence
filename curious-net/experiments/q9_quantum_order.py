"""Q9: when does a quantum-state predictor beat a classical one? Sequential yes/no questions A and B, asked in either order.
Generators: (Q) quantum: a qubit state (theta) measured by question A in the computational basis and question B in a basis rotated by phi (2 parameters; satisfies the QQ equality
p(a0,b1)+p(a1,b0) = p(b0,a1)+p(b1,a0) automatically; Wang & Busemeyer 2013); (C-shared) classical order-independent joint over (A,B) (random Dirichlet); (C-order) classical with a SEPARATE joint per
order (violates the QQ equality in general). Models (all scored by exact Bayesian prequential code length, bits per trial): quantum (uniform prior over a 40x40 grid of (theta, phi)),
classical-shared (Dirichlet(1/2) over the 4 joint cells), classical-order (a separate Dirichlet(1/2) joint per order). 300 random datasets per cell; order is random per trial."""
import numpy as np

rng = np.random.default_rng(0)
GRID = 40
TH = (np.arange(GRID) + 0.5) * np.pi / GRID
PH = (np.arange(GRID) + 0.5) * np.pi / GRID
CELLS = [(a, b) for a in (0, 1) for b in (0, 1)]                  # outcome encoding: (answer to A, answer to B); 1 = yes


def quantum_joint(theta, phi):
    """returns joint[order][(a,b)] for order 0 = A then B, 1 = B then A (answers indexed by question, not by position)"""
    pa1 = np.cos(theta / 2) ** 2                                   # P(A yes first)
    pb1_given_a1, pb1_given_a0 = np.cos(phi / 2) ** 2, np.sin(phi / 2) ** 2
    ab = {}
    for a in (0, 1):
        for b in (0, 1):
            pa = pa1 if a == 1 else 1 - pa1
            pb = pb1_given_a1 if a == 1 else pb1_given_a0
            ab[(a, b)] = pa * (pb if b == 1 else 1 - pb)
    pb1 = np.cos((theta - phi) / 2) ** 2                          # P(B yes first)
    pa1_given_b1, pa1_given_b0 = np.cos(phi / 2) ** 2, np.sin(phi / 2) ** 2
    ba = {}
    for a in (0, 1):
        for b in (0, 1):
            pb_ = pb1 if b == 1 else 1 - pb1
            pa_ = pa1_given_b1 if b == 1 else pa1_given_b0
            ba[(a, b)] = pb_ * (pa_ if a == 1 else 1 - pa_)
    return [ab, ba]


def gen_data(kind, n, rng):
    if kind == "quantum":
        th, ph = rng.uniform(0.3, np.pi - 0.3), rng.uniform(0.3, np.pi - 0.3)
        J = quantum_joint(th, ph)
        Jm = [np.array([J[o][c] for c in CELLS]) for o in (0, 1)]
    elif kind == "classical_shared":
        d = rng.dirichlet(np.ones(4))
        Jm = [d, d]
    else:
        Jm = [rng.dirichlet(np.ones(4)), rng.dirichlet(np.ones(4))]
    orders = rng.integers(0, 2, n)
    cells = np.array([rng.choice(4, p=Jm[o]) for o in orders])
    return orders, cells, Jm


def code_len_classical(orders, cells, shared):
    counts = np.full((1 if shared else 2, 4), 0.5)
    L = 0.0
    for o, c in zip(orders, cells):
        k = 0 if shared else o
        L += -np.log2(counts[k, c] / counts[k].sum())
        counts[k, c] += 1
    return L


def grid_joint_table():
    """P(cell | order) for every grid point: shape (GRID, GRID, 2, 4)"""
    T = np.zeros((GRID, GRID, 2, 4))
    for i, th in enumerate(TH):
        for j, ph in enumerate(PH):
            J = quantum_joint(th, ph)
            for o in (0, 1):
                T[i, j, o] = [J[o][c] for c in CELLS]
    return T


GT = grid_joint_table()


def code_len_quantum(orders, cells):
    logw = np.zeros((GRID, GRID))
    L = 0.0
    for o, c in zip(orders, cells):
        w = np.exp(logw - logw.max()); w /= w.sum()
        pred = float((w * GT[:, :, o, c]).sum())
        L += -np.log2(max(pred, 1e-12))
        logw += np.log(np.maximum(GT[:, :, o, c], 1e-12))
    return L


if __name__ == "__main__":
    print("bits per trial (mean over 300 datasets; lower = better) | which model has the lowest code length most often")
    for kind in ("quantum", "classical_shared", "classical_order"):
        print(f"-- data generated by: {kind}")
        for n in (20, 50, 200, 1000):
            res = {"quantum": [], "classical_shared": [], "classical_order": []}
            wins = {"quantum": 0, "classical_shared": 0, "classical_order": 0}
            qq = []
            for _ in range(300):
                orders, cells, Jm = gen_data(kind, n, rng)
                L = {"quantum": code_len_quantum(orders, cells) / n, "classical_shared": code_len_classical(orders, cells, True) / n,
                     "classical_order": code_len_classical(orders, cells, False) / n}
                for k in L:
                    res[k].append(L[k])
                wins[min(L, key=L.get)] += 1
                qq.append(abs((Jm[0][1] + Jm[0][2]) - (Jm[1][1] + Jm[1][2])))        # |p(a0,b1)+p(a1,b0) in order AB - same in order BA|: 0 under the QQ equality
            print(f"   n={n:5d}  quantum {np.mean(res['quantum']):.3f}  classical-shared {np.mean(res['classical_shared']):.3f}  classical-order {np.mean(res['classical_order']):.3f}"
                  f"   wins q/c-shared/c-order = {wins['quantum']}/{wins['classical_shared']}/{wins['classical_order']}   mean |QQ violation| of the generator {np.mean(qq):.3f}")
