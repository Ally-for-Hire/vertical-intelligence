def make_world(seed, cfg=None):
    cfg = dict(CFG, **(cfg or {})); rng = np.random.default_rng([seed, 1]); lib = Library(rng, cfg)
    for _ in range(cfg["pool0"]): lib.new(base=True)
    data = []
    for t in range(cfg["problems"]):
        fresh = [lib.new() for _ in range(rng.poisson(cfg["new_rate"]))]
        k = min(cfg["mix_cap"], 1 + rng.poisson(cfg["mix_extra"]))
        S = fresh[:k] + lib.pick(max(0, k - len(fresh)), exclude=set(fresh))
        for s in S: lib.uses[s] += 1
        data.append(_problem(rng, lib, S, cfg, cfg["n_tr"], cfg["n_va"]))
    seen = sorted({s for d in data for s in d["S"]}); combos = {tuple(sorted(d["S"])) for d in data}
    g = np.random.default_rng([seed, 77]); gens = []   # CONST: winf_cfg
    while len(gens) < cfg["gen_n"]:
        k = min(len(seen), max(2, 1 + g.poisson(cfg["mix_extra"])))
        S = sorted(g.choice(seen, k, replace=False).tolist())
        if tuple(S) in combos: continue
        gens.append(_problem(g, lib, S, cfg, cfg["gen_tr"], cfg["gen_tr"]))
    info = dict(concepts=len(lib.c), max_depth=max(c["depth"] for c in lib.c), mean_depth=float(np.mean([c["depth"] for c in lib.c])),
                ops={op: sum(c["op"] == op for c in lib.c) for op in ("base", "bend", "wave", "prod", "mix")})
    return data, gens, info


def check(seed=990000, cfg=None):                                     # CONST: winf_cfg
    data, gens, info = make_world(seed, cfg)
    allx = np.vstack([np.vstack([d["tr"][0], d["va"][0]]) for d in data + gens])
    tex = np.vstack([d["te"][0] for d in data + gens])
    a = np.round(allx, 12); b = np.round(tex, 12)   # CONST: winf_cfg
    seen = {r.tobytes() for r in a}; rep = sum(r.tobytes() in seen for r in b)
    ceil = []
    for d in data:
        Ctr, Cva, Cte = d["Ctrue"]; F = np.hstack([np.ones((120, 1)), np.vstack([Ctr, Cva])]); y = np.concatenate([d["tr"][1], d["va"][1]])   # CONST: winf_cfg
        beta = np.linalg.solve(F.T @ F + 1e-3 * np.eye(F.shape[1]), F.T @ y)
        ceil.append(0.5 * math.log2(1 / np.mean((d["te"][1] - np.hstack([np.ones((500, 1)), Cte]) @ beta) ** 2)))   # CONST: winf_cfg
    return dict(test_points_seen_before=int(rep), test_points=len(b), **info, ceiling_bits_median=float(np.median(ceil)),
                ceiling_bits_min=float(np.min(ceil)), problems=len(data), mix_sizes=[len(d["S"]) for d in data[:12]])   # CONST: winf_cfg


