"""winf.py: a near-infinitely complex world where memorising is useless (author, 2026-11-02: 'i want it to work on a near infinitely complex world
frankly. i don't want any learned system to be able to memorize anything no matter the compute').

What 'cannot be memorised' means here (no finite world is unmemorisable in principle): NOTHING EVER REPEATS. Inputs are continuous and every point is
drawn fresh, so no test point equals any point ever shown; problems never repeat (continuous mixing weights, an ever-growing concept library); the
only thing worth keeping is the world's STRUCTURE (the concepts and how they compose), which is what learning should find.
Structure:
  * concepts form an unbounded library generated by a grammar: a base concept is tanh(w.x + b); a composite is built on 1-2 EARLIER concepts
    (op: bend tanh(a*c + w.x/2 + b), product c1*c2, mix tanh(a1*c1 + a2*c2 + b), wave sin(f*c + b)); every concept is standardised once on a fixed
    reference sample, so depth can grow without the values exploding or vanishing;
  * every problem brings Poisson(new_rate) new concepts; parents and problem members are drawn by POPULARITY (rich-get-richer: a concept is picked
    with weight 1 + times used), so some structure is reused a lot and there is a long tail;
  * a problem mixes 1 + Poisson(mix_extra) concepts (cap mix_cap), always including its new ones, with continuous weights, plus 10% noise.
Data format matches vi/x1_10.py (tr, va, te, S, Ctrue) so every learner runs unchanged. gen_problems(): new combinations of seen concepts, 20 points.
Usage: python winf.py      (self-check: no repeated points, depth grows, ceilings sane)"""
import sys as _s, pathlib as _p; _s.path.insert(0, str(next(q for q in _p.Path(__file__).resolve().parents if (q / 'core' / 'vipaths.py').exists()) / 'core')); import vipaths  # vi-bootstrap
import math
import numpy as np

CFG = dict(dim=8, problems=60, pool0=3, new_rate=0.8, p_base=0.25, mix_extra=1.5, mix_cap=6, a_lo=0.5, a_hi=1.5, noise=0.1,   # CONST: winf_cfg
           n_tr=60, n_va=60, n_te=500, ref_n=2000, gen_n=10, gen_tr=20, gain=2.0)   # CONST: winf_cfg


class Library:
    def __init__(self, rng, cfg):
        self.rng, self.cfg, self.c, self.uses = rng, cfg, [], []
        self.ref = rng.standard_normal((cfg["ref_n"], cfg["dim"]))
        self.ref_vals = np.zeros((cfg["ref_n"], 0))

    def _raw(self, k, x, vals):
        op, par, p = self.c[k]["op"], self.c[k]["par"], self.c[k]["p"]
        if op == "base": return np.tanh(x @ p["w"] + p["b"])
        a = vals[:, par[0]]
        if op == "bend": return np.tanh(p["a"] * a + 0.5 * (x @ p["w"]) + p["b"])
        if op == "wave": return np.sin(p["f"] * a + p["b"])
        b = vals[:, par[1]]
        if op == "prod": return a * b
        return np.tanh(p["a1"] * a + p["a2"] * b + p["b"])               # mix

    def pick(self, n, exclude=()):
        w = np.array([0.0 if i in exclude else 1.0 + u for i, u in enumerate(self.uses)])
        n = min(n, int((w > 0).sum()))
        return list(self.rng.choice(len(w), n, replace=False, p=w / w.sum())) if n else []

    def new(self, base=False):
        r, m = self.rng, self.cfg["dim"]
        w = r.standard_normal(m) * self.cfg["gain"] / math.sqrt(m)
        if base or len(self.c) < 1 or r.random() < self.cfg["p_base"]: op, par, p = "base", (), dict(w=w, b=r.standard_normal() * 0.5)
        else:
            op = ["bend", "wave", "prod", "mix"][r.integers(4)]
            if op in ("prod", "mix") and len(self.c) < 2: op = "bend"
            par = tuple(self.pick(1 if op in ("bend", "wave") else 2))
            sgn = lambda: float(r.choice([-1, 1]) * r.uniform(1.0, 2.0))
            p = dict(w=w, b=r.standard_normal() * 0.5, a=sgn(), f=float(r.uniform(1.0, 3.0)), a1=sgn(), a2=sgn())   # CONST: winf_cfg
        self.c.append(dict(op=op, par=par, p=p, mu=0.0, sd=1.0, depth=0 if not par else 1 + max(self.c[q]["depth"] for q in par)))
        self.uses.append(0)
        k = len(self.c) - 1
        raw = self._raw(k, self.ref, self.ref_vals)
        self.c[k]["mu"], self.c[k]["sd"] = float(raw.mean()), float(raw.std() + 1e-9)
        self.ref_vals = np.hstack([self.ref_vals, ((raw - self.c[k]["mu"]) / self.c[k]["sd"])[:, None]])
        return k

    def values(self, x, upto=None):
        n = len(self.c) if upto is None else upto
        V = np.zeros((len(x), n))
        for k in range(n): V[:, k] = (self._raw(k, x, V) - self.c[k]["mu"]) / self.c[k]["sd"]
        return V


def _problem(rng, lib, S, cfg, n_tr, n_va):
    a = rng.choice([-1, 1], len(S)) * rng.uniform(cfg["a_lo"], cfg["a_hi"], len(S))
    n = n_tr + n_va + cfg["n_te"] + cfg["ref_n"]
    x = rng.standard_normal((n, cfg["dim"])); V = lib.values(x)[:, S]
    y = V @ a; y = y + rng.standard_normal(n) * cfg["noise"] * y.std()
    mu, sd = y[-cfg["ref_n"]:].mean(), y[-cfg["ref_n"]:].std(); y = (y - mu) / sd
    i1, i2, i3 = n_tr, n_tr + n_va, n_tr + n_va + cfg["n_te"]
    return dict(tr=(x[:i1], y[:i1]), va=(x[i1:i2], y[i1:i2]), te=(x[i2:i3], y[i2:i3]), S=list(S), Ctrue=(V[:i1], V[i1:i2], V[i2:i3]))


def make_finite_world(seed, cfg=None):
    """FINITE world (author ruling 2026-11-02: 'the world cannot expand. it needs to be finitely complex ... and then it must be expanded').
    Phase A: the whole library (lib_size concepts, same grammar) exists BEFORE the stream and never changes; problems mix concepts from it by
    popularity. Phase B (expansion, if expand_n > 0): after expand_at problems the library grows ONCE by expand_n concepts built on the old ones,
    and each later problem includes one new concept with probability p_new_after. Points and mixing weights are always fresh."""
    cfg = dict(CFG, **(cfg or {})); rng = np.random.default_rng([seed, 1]); lib = Library(rng, cfg)
    for _ in range(cfg["pool0"]): lib.new(base=True)
    while len(lib.c) < cfg["lib_size"]: lib.new()
    nA = len(lib.c); data = []; newset = []
    for t in range(cfg["expand_at"] + cfg["after_n"]):
        if t == cfg["expand_at"] and cfg["expand_n"] > 0:
            newset = [lib.new() for _ in range(cfg["expand_n"])]
        k = min(cfg["mix_cap"], 1 + rng.poisson(cfg["mix_extra"]))
        lead = []
        if newset and rng.random() < cfg["p_new_after"]:
            w = np.array([1.0 + lib.uses[i] for i in newset]); lead = [int(rng.choice(newset, p=w / w.sum()))]
        avail = set(range(len(lib.c))) if newset else set(range(nA))
        S = lead + lib.pick(max(0, k - len(lead)), exclude=set(lead) | (set(range(len(lib.c))) - avail))
        for s in S: lib.uses[s] += 1
        d = _problem(rng, lib, S, cfg, cfg["n_tr"], cfg["n_va"]); d["phase"] = int(t >= cfg["expand_at"]); d["has_new"] = bool(set(S) & set(newset))
        data.append(d)
    seen = sorted({s for d in data for s in d["S"]}); combos = {tuple(sorted(d["S"])) for d in data}
    g = np.random.default_rng([seed, 77]); gens = []   # CONST: winf_cfg
    while len(gens) < cfg["gen_n"]:
        k = min(len(seen), max(2, 1 + g.poisson(cfg["mix_extra"])))
        S = sorted(g.choice(seen, k, replace=False).tolist())
        if tuple(S) in combos: continue
        gens.append(_problem(g, lib, S, cfg, cfg["gen_tr"], cfg["gen_tr"]))
    info = dict(concepts_A=nA, concepts=len(lib.c), max_depth=max(c["depth"] for c in lib.c), max_depth_A=max(c["depth"] for c in lib.c[:nA]),
                used_A=len({s for d in data if not d["phase"] for s in d["S"]}))
    return data, gens, info


